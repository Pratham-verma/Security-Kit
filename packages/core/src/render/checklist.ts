// The security plan as a checklist people work through by hand, and as a prompt for AI coding tools.
import type { Control, Manifest, ResolvedPlan, Severity, Standards } from '../types.js';
import { componentHeading, LEVEL_LABELS, STANDARD_LABELS } from './format.js';

const SEVERITIES: Severity[] = ['critical', 'high', 'medium', 'low'];
const PLATFORM_LABELS: Record<string, string> = { web: 'Web frontend', backend: 'Backend / API', android: 'Android', ios: 'iOS', cloud: 'Cloud (AWS)' };
const SENSITIVITY_LABELS: Record<string, string> = {
  low: 'low (public content, no personal data)',
  medium: 'medium (accounts, emails, basic personal data)',
  high: 'high (payments, health, government IDs or confidential data)',
};
const HELPER_LABELS: Record<string, string> = { node: 'Node.js (@seckit/node)', web: 'Browser (@seckit/web)', android: 'Android', ios: 'iOS' };

export interface ChecklistItem {
  id: string;
  title: string;
  severity: Severity;
  /** How to verify it is done. */
  check: string[];
  /** How to implement it (markdown). */
  howTo: string;
  /** Platform-specific helpers, e.g. "Node.js (@seckit/node)": "hashPassword()". */
  helpers: { label: string; text: string }[];
  /** One-line rule, as given to AI assistants. */
  rule: string;
  /** Concrete test cases (commands and expected results), when the control has them. */
  tests: string[];
  references: string[];
}

export interface ChecklistSection {
  title: string;
  /** 'app' for parts of the code, 'cloud' for the cloud account and services. */
  category: 'app' | 'cloud';
  description: string;
  items: ChecklistItem[];
}

export interface Checklist {
  app: ResolvedPlan['app'];
  sections: ChecklistSection[];
  total: number;
  bySeverity: Record<Severity, number>;
}

function references(s: Standards): string[] {
  return (Object.entries(s) as [keyof Standards, string[]][]).flatMap(([key, ids]) =>
    ids.map((id) => (key === 'cwe' || key === 'nist' ? id : `${STANDARD_LABELS[key].replace(/ \(.*\)$/, '')} ${id}`)),
  );
}

function item(c: Control): ChecklistItem {
  return {
    id: c.id,
    title: c.title,
    severity: c.severity,
    check: c.verify.map((v) => v.description),
    howTo: c.guidance.trim(),
    helpers: Object.entries(c.implement ?? {}).map(([k, v]) => ({ label: HELPER_LABELS[k] ?? k, text: v ?? '' })),
    rule: c.ai_rule,
    tests: c.tests ?? [],
    references: references(c.standards),
  };
}

/** One section per component (instance), most severe first; each control appears once. */
export function buildChecklist(plan: ResolvedPlan, opts: { minSeverity?: Severity } = {}): Checklist {
  const limit = SEVERITIES.indexOf(opts.minSeverity ?? 'low');
  const seen = new Set<string>();
  const sections: ChecklistSection[] = [];
  for (const c of plan.components) {
    const items = c.controls
      .filter((x) => !seen.has(x.id) && SEVERITIES.indexOf(x.severity) <= limit)
      .sort((a, b) => SEVERITIES.indexOf(a.severity) - SEVERITIES.indexOf(b.severity))
      .map(item);
    items.forEach((i) => seen.add(i.id));
    if (items.length > 0) sections.push({ title: componentHeading(c), category: c.component.category ?? 'app', description: c.component.description, items });
  }
  const all = sections.flatMap((s) => s.items);
  const bySeverity = { critical: 0, high: 0, medium: 0, low: 0 };
  for (const i of all) bySeverity[i.severity]++;
  return { app: plan.app, sections, total: all.length, bySeverity };
}

const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const oneLine = (md: string) => md.replace(/\s*\n\s*/g, ' ').trim();

/** Markdown task list (GitHub-style `- [ ]`), ticked from `done`. */
export function renderChecklistMarkdown(list: Checklist, version: string, done: Set<string> = new Set()): string {
  const ticked = list.sections.flatMap((s) => s.items).filter((i) => done.has(i.id)).length;
  const lines = [
    `# Security checklist — ${list.app.name}`,
    '',
    `> Generated by Security Kit ${version} for ${list.app.platforms.map((p) => PLATFORM_LABELS[p] ?? p).join(', ')} · level ${list.app.assurance_level} · ${list.total} checks (${SEVERITIES.filter((s) => list.bySeverity[s] > 0).map((s) => `${list.bySeverity[s]} ${s}`).join(', ')}).`,
    `> Progress: ${ticked} of ${list.total} done.`,
    '',
    'Work top to bottom: each section lists its most severe items first. Tick an item only when it is',
    'implemented **and** you checked it the way "Check" describes.',
    '',
  ];
  for (const section of list.sections) {
    lines.push(`## ${section.title}`, '', `_${section.description}_`, '');
    for (const i of section.items) {
      lines.push(`- [${done.has(i.id) ? 'x' : ' '}] **${i.id} · ${cap(i.severity)} — ${i.title}**`);
      for (const c of i.check) lines.push(`  - Check: ${c}`);
      for (const c of i.tests) lines.push(`  - Test: ${c}`);
      lines.push(`  - How: ${oneLine(i.howTo)}`);
      for (const h of i.helpers) lines.push(`  - ${h.label}: ${h.text}`);
      if (i.references.length > 0) lines.push(`  - Standards: ${i.references.join(', ')}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

export type PromptMode = 'audit' | 'build' | 'test';

function aboutApp(plan: ResolvedPlan, manifest: Manifest): string[] {
  const lines = [
    `- Name: ${plan.app.name}`,
    `- Runs on: ${plan.app.platforms.map((p) => PLATFORM_LABELS[p] ?? p).join(', ')}`,
    `- Most sensitive data: ${SENSITIVITY_LABELS[manifest.app.data_sensitivity ?? 'medium']}`,
    `- Security level: ${plan.app.assurance_level} of 3 (OWASP ASVS) — ${LEVEL_LABELS[plan.app.assurance_level]}`,
    '- Parts of the app:',
  ];
  for (const c of plan.components) {
    const options = Object.entries(c.instance)
      .filter(([k]) => k !== 'type' && k !== 'name')
      .map(([k, v]) => `${k.replace(/_/g, ' ')}: ${Array.isArray(v) ? v.join(', ') : String(v)}`.replace(/_/g, ' '));
    lines.push(`  - ${componentHeading(c)}${options.length > 0 ? ` — ${options.join('; ')}` : ''}`);
  }
  return lines;
}

const AUDIT_STEPS = `## How to work

1. **Explore first, change nothing yet.** Find the entry points, routes/controllers, authentication, data
   access, configuration, dependencies and build/deploy files.
2. **Check every item** in the checklist below and give each one a result:
   - **PASS** — implemented correctly. Cite the evidence as \`file:line\`.
   - **FAIL** — missing or wrong. Cite \`file:line\` and explain the risk in one sentence.
   - **N/A** — does not apply to this codebase. Say why.
   - **UNSURE** — needs a human decision or information you do not have. Say what to check.
3. **Fix every FAIL**, critical first, then high, medium, low:
   - Make the smallest change that fully fixes it. Follow the project's existing style, framework and libraries.
   - Prefer the framework's built-in protections and well-maintained libraries over custom security code.
   - Add or update tests that prove the fix.
   - Never weaken a protection to make something work, never hard-code secrets, never disable tests, linters
     or security checks.
   - If a fix needs a product decision, new infrastructure or a risky data migration, do not guess — list it
     under "Needs a decision" instead.
4. **Report back** when every item has a result:
   - A table: \`| ID | Check | Severity | Result (PASS / FIXED / N/A / UNSURE) | Evidence or change |\`
   - **Needs a decision:** what a human must handle, and why.
   - How to run the tests you added or changed.

If the checklist is long, work section by section, but do not stop until every item has a result.`;

const BUILD_STEPS = `## How to work

These are standing rules for every change you make in this repository from now on.

1. **Before writing code** for a task, find the checklist items that apply to it (by section and topic).
2. **Implement them as part of the task** — not as a later TODO. Use the framework's built-in protections and
   well-maintained libraries; do not write custom crypto or security code.
3. **Never** hard-code secrets, log passwords or tokens, build SQL or shell commands from user input, disable
   TLS verification, or weaken an existing protection to make something work.
4. **Add tests** for the security behaviour you implement (e.g. "rejects a request without a valid session").
5. **When you finish a task**, list the checklist IDs you applied, and any item you could not apply and why.
6. If a rule conflicts with what you are asked to do, stop and ask instead of guessing.`;

const TEST_STEPS = `## How to work

Your job is to **test** this application against the checklist below and report the results. Do not change
any code, configuration or cloud resource while testing.

1. **Explore first.** Find the entry points, routes, authentication, data access, configuration, dependencies,
   infrastructure code (Terraform, CloudFormation, CDK, Kubernetes, Dockerfiles) and CI files.
2. **Run every test case** listed under an item. When an item has no test cases, design one from its "Verify"
   line — for example a unit or integration test, a \`curl\` request against a local instance, or a code search.
   - Write new automated tests only in the project's test folders, with its existing test framework.
   - Run commands against local or test environments only. Never against production unless the user says so.
   - Cloud commands (\`aws …\`) must be **read-only** (\`describe\`, \`get\`, \`list\`). If no credentials are
     configured, check the infrastructure code instead and say the live test is still to be run.
3. **Give each item a result:**
   - **PASS** — every test passed. Show the command or test and the evidence (\`file:line\` or output).
   - **FAIL** — a test failed. Show what failed and the risk in one sentence.
   - **N/A** — does not apply to this application. Say why.
   - **NOT RUN** — could not be tested here (no access, needs a human). Say exactly what to run.
4. **Report back:**
   - A table: \`| ID | Check | Severity | Result (PASS / FAIL / N/A / NOT RUN) | Test and evidence |\`
   - The failing items, most severe first, with the fix you recommend (do not apply it).
   - How to run the tests you wrote.`;

// Security changes must not break the app: the controls below are the ones that most often block real users
// when applied naively, so the prompt says how to roll each one out compatibly.
const KEEP_WORKING = `## Keep the app working

Security changes must not break what the application does today.

- **Before changing anything**, find how to build and test the project and run the existing tests. Note any that
  already fail, so you do not mistake them for your own breakage.
- **Keep behaviour stable:** existing features, routes, API request and response formats, stored data and user
  flows keep working. Do not rename or remove public endpoints, fields or settings to fix an item.
- **Roll out protections that can block real users compatibly:**
  - Content-Security-Policy: allow every script, style, font, image and API origin the app really uses; if unsure,
    ship it in report-only mode first.
  - CORS: allow every origin the app's own web and mobile clients use.
  - Rate limits and request or upload size limits: set them well above normal use and return a clear error.
  - Password policy: apply new rules when a password is set or changed; never lock out existing users.
  - Password hashing: upgrade old hashes when each user next signs in, instead of invalidating them.
  - Sessions and tokens: do not sign every user out unless the item requires it.
  - Encryption at rest and new database constraints: migrate existing data so it stays readable.
- **After each fix**, build and run the tests again. If a fix would change behaviour users rely on, do not apply
  it — list it under "Needs a decision" with the trade-off.`;

const CLOUD_NOTE = `## Cloud checks

Some items cover the app's AWS account and services. Check them in the infrastructure code first (Terraform,
CloudFormation, CDK, SAM, Serverless). The "Test" lines are AWS CLI commands with the expected result. Only run
read-only commands (\`describe\`, \`get\`, \`list\`), and only if AWS credentials are configured and the user
agrees. Fix cloud problems in the infrastructure code, never by changing live resources directly.`;

/** A self-contained prompt for Claude Code, Cursor, Copilot, Gemini CLI, Codex and other AI coding tools. */
export function renderAiPrompt(plan: ResolvedPlan, manifest: Manifest, opts: { mode?: PromptMode; minSeverity?: Severity } = {}): string {
  const mode = opts.mode ?? 'audit';
  const list = buildChecklist(plan, { minSeverity: opts.minSeverity });
  const standards = (manifest.standards ?? []).map((s) => STANDARD_LABELS[s as keyof Standards]).filter(Boolean);
  const scope = opts.minSeverity && opts.minSeverity !== 'low' ? ` (${SEVERITIES.slice(0, SEVERITIES.indexOf(opts.minSeverity) + 1).join(' and ')} only)` : '';

  const cloud = list.sections.some((s) => s.category === 'cloud');

  const lines = [
    {
      audit: `# Security review and hardening — ${plan.app.name}`,
      build: `# Security rules for building ${plan.app.name}`,
      test: `# Security tests — ${plan.app.name}`,
    }[mode],
    '',
    {
      audit: 'You are a senior application security engineer working in this repository. Review the code against the security checklist below, fix what is missing or wrong, and report back.',
      build: 'You are a senior engineer who writes secure code by default. Follow the security checklist below in every change you make in this repository.',
      test: 'You are a senior security tester working in this repository. Test the application against the security checklist below and report the results, without changing anything.',
    }[mode],
    '',
    '## About this application',
    '',
    ...aboutApp(plan, manifest),
    '',
    { audit: AUDIT_STEPS, build: BUILD_STEPS, test: TEST_STEPS }[mode],
    '',
    ...(mode === 'test' ? [] : [KEEP_WORKING, '']),
    ...(cloud ? [CLOUD_NOTE, ''] : []),
    `## Security checklist — ${list.total} items${scope}`,
    '',
    `Tailored to this app by Security Kit${standards.length > 0 ? ` and mapped to ${standards.join(', ')}` : ''}. Each item gives the rule, how to verify it${list.sections.some((s) => s.items.some((i) => i.tests.length > 0)) ? ', test cases' : ''} and references.`,
    '',
  ];
  for (const section of list.sections) {
    lines.push(`### ${section.title}`, '');
    for (const i of section.items) {
      lines.push(`- **${i.id}** (${i.severity}) — ${i.title}`);
      lines.push(`  - Rule: ${i.rule}`);
      for (const c of i.check) lines.push(`  - Verify: ${c}`);
      if (i.tests.length > 0) {
        lines.push('  - Test cases:');
        for (const c of i.tests) lines.push(`    - ${c}`);
      }
      if (i.references.length > 0) lines.push(`  - Refs: ${i.references.join(', ')}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}
