import type { Manifest, ResolvedPlan, Severity, Standards } from '../types.js';
import { AI_CHOICES } from '../choices.js';
import { componentHeading, escapeCell, formatStandards, LEVEL_LABELS, STANDARD_LABELS, uniqueControls } from './format.js';
import { AI_FILES } from './ai-rules.js';

const SEVERITIES: Severity[] = ['critical', 'high', 'medium', 'low'];

function optionsLine(instance: Record<string, unknown>): string {
  const parts = Object.entries(instance)
    .filter(([k]) => k !== 'type' && k !== 'name')
    .map(([k, v]) => `\`${k}: ${Array.isArray(v) ? v.join(', ') : String(v)}\``);
  return parts.join(' · ');
}

function coverage(plan: ResolvedPlan, manifest: Manifest): string[] {
  const wanted = manifest.standards;
  const byStandard = new Map<keyof Standards, Map<string, Set<string>>>();
  for (const { control } of uniqueControls(plan)) {
    for (const [key, ids] of Object.entries(control.standards) as [keyof Standards, string[]][]) {
      if (wanted && !wanted.includes(key)) continue;
      const map = byStandard.get(key) ?? new Map<string, Set<string>>();
      for (const id of ids) map.set(id, (map.get(id) ?? new Set()).add(control.id));
      byStandard.set(key, map);
    }
  }

  const lines: string[] = [];
  for (const key of Object.keys(STANDARD_LABELS) as (keyof Standards)[]) {
    const map = byStandard.get(key);
    if (!map) continue;
    lines.push(`### ${STANDARD_LABELS[key]}`, '', '| Requirement | Controls |', '|---|---|');
    const ids = [...map.keys()].sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
    for (const id of ids) lines.push(`| ${id} | ${[...map.get(id)!].join(', ')} |`);
    lines.push('');
  }
  return lines;
}

/** `checks` maps control ID -> IDs of the automated checks `seckit audit` runs for it. */
export function renderPlanMarkdown(plan: ResolvedPlan, manifest: Manifest, version: string, checks: Map<string, string[]> = new Map()): string {
  const { app } = plan;
  const assistants = manifest.ai_assistants ?? ['agents_md'];
  const L: string[] = [];

  L.push(
    `# Security plan: ${app.name}`,
    '',
    `> Generated by Security Kit ${version} from \`seckit.yaml\`. Do not edit this file —`,
    '> change `seckit.yaml` and run `npx seckit generate` again.',
    '',
    '| | |',
    '|---|---|',
    `| Platforms | ${app.platforms.join(', ')} |`,
    `| Assurance level | ${app.assurance_level} — ${LEVEL_LABELS[app.assurance_level]} |`,
    `| Data sensitivity | ${app.data_sensitivity ?? 'medium'} |`,
    ...(manifest.standards ? [`| Standards | ${manifest.standards.map((s) => STANDARD_LABELS[s as keyof Standards] ?? s).join(', ')} |`] : []),
    '',
    '## Summary',
    '',
    '| Component | Threats | Controls | Critical | High | Medium | Low |',
    '|---|---|---|---|---|---|---|',
  );

  const totals = { threats: 0, controls: 0, ...Object.fromEntries(SEVERITIES.map((s) => [s, 0])) } as Record<string, number>;
  for (const c of plan.components) {
    const counts = SEVERITIES.map((s) => c.controls.filter((x) => x.severity === s).length);
    L.push(`| ${componentHeading(c)} | ${c.threats.length} | ${c.controls.length} | ${counts.join(' | ')} |`);
    totals.threats! += c.threats.length;
    totals.controls! += c.controls.length;
    SEVERITIES.forEach((s, i) => (totals[s]! += counts[i]!));
  }
  L.push(`| **Total** | **${totals.threats}** | **${totals.controls}** | ${SEVERITIES.map((s) => `**${totals[s]}**`).join(' | ')} |`, '');

  L.push(
    '## How to use this plan',
    '',
    '1. Implement every control below, critical ones first. Each control maps to the standards it satisfies.',
    '2. Run `npx seckit audit` to check the code automatically; use the **Verify** steps for the rest.',
    `3. AI coding assistants receive these rules automatically via: ${assistants
      .map((a) => `${AI_CHOICES.find((c) => c.value === a)?.label ?? a} (\`${AI_FILES[a].path}\`)`)
      .join(', ')}.`,
    '4. Run `npx seckit explain <ID>` for details on any threat or control.',
    '',
  );

  for (const c of plan.components) {
    L.push(`## ${componentHeading(c)}`, '');
    const opts = optionsLine(c.instance);
    if (opts) L.push(opts, '');

    L.push('### Threats', '', '| ID | Threat | STRIDE | CWE |', '|---|---|---|---|');
    for (const t of c.threats) {
      L.push(`| ${t.id} | ${escapeCell(t.title)} | ${t.stride.join('')} | ${(t.cwe ?? []).join(', ')} |`);
    }
    L.push('', '### Controls', '');

    for (const ctl of c.controls) {
      L.push(
        `#### ${ctl.id} · ${ctl.title}`,
        '',
        `**Severity:** ${ctl.severity} · **Level:** ${ctl.level} · **Mitigates:** ${ctl.mitigates.join(', ')}` +
          ` · **Platforms:** ${(ctl.platforms ?? c.component.platforms).filter((p) => app.platforms.includes(p)).join(', ')}`,
        '',
        `**Standards:** ${formatStandards(ctl.standards)}`,
        '',
        ctl.guidance.trim(),
        '',
        ...(ctl.implement?.node ? [`**Implement with \`@seckit/node\`:** ${ctl.implement.node}`, ''] : []),
        ...(ctl.implement?.web ? [`**Implement with \`@seckit/web\`:** ${ctl.implement.web}`, ''] : []),
        ...(ctl.implement?.android && app.platforms.includes('android') ? [`**On Android:** ${ctl.implement.android}`, ''] : []),
        ...(ctl.implement?.ios && app.platforms.includes('ios') ? [`**On iOS:** ${ctl.implement.ios}`, ''] : []),
        '**Verify**',
        '',
        ...ctl.verify.map((v) => `- _${v.type}_ — ${v.description}`),
        checks.has(ctl.id)
          ? `- _automated_ — \`seckit audit\` checks this (${checks.get(ctl.id)!.map((c) => `\`${c}\``).join(', ')})`
          : '- _automated_ — none yet; verify manually',
        '',
      );
    }
  }

  L.push('## Standards coverage', '', 'Requirements addressed by this plan, and the controls that address them.', '');
  L.push(...coverage(plan, manifest));

  return L.join('\n').trimEnd() + '\n';
}
