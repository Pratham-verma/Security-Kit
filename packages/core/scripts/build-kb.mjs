// Compiles the knowledge base for the browser build (src/generated/):
//  - kb-data.ts: components, plus which controls each Semgrep rule checks
//  - validators.ts: JSON Schema validators pre-compiled with Ajv standalone, so the browser never needs eval
//    (the hosted app's CSP forbids 'unsafe-eval').
// Run by `npm run build`; core tests fail if the committed files are stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { parse } from 'yaml';

const root = new URL('../../../', import.meta.url);
const read = (rel) => readFileSync(new URL(rel, root), 'utf8');
const HEADER = '// Generated by packages/core/scripts/build-kb.mjs from knowledge-base/ and schemas/. Do not edit.\n';

export function generate() {
  const componentsDir = new URL('knowledge-base/components/', root);
  const components = readdirSync(componentsDir)
    .filter((f) => /\.ya?ml$/.test(f))
    .sort()
    .map((f) => parse(readFileSync(new URL(f, componentsDir), 'utf8')));

  const rulesDir = new URL('knowledge-base/rules/semgrep/', root);
  const ruleControls = {};
  for (const f of readdirSync(rulesDir).filter((f) => /\.ya?ml$/.test(f)).sort()) {
    for (const rule of parse(readFileSync(new URL(f, rulesDir), 'utf8'))?.rules ?? []) {
      ruleControls[rule.id] = rule.metadata['seckit-controls'];
    }
  }

  const kbData =
    HEADER +
    "import type { Component } from '../types.js';\n\n" +
    `export const KB_COMPONENTS = ${JSON.stringify(components, null, 1)} as unknown as Component[];\n\n` +
    '/** Semgrep rule ID -> controls it checks (the rules themselves only run in the CLI). */\n' +
    `export const RULE_CONTROLS: Record<string, string[]> = ${JSON.stringify(ruleControls, null, 1)};\n`;

  // Same settings as createAjv() in src/node.ts, plus standalone ESM output.
  const ajv = new Ajv2020({ allErrors: true, useDefaults: true, strict: false, code: { source: true, esm: true } });
  const exportsMap = {};
  ajv.addSchema(JSON.parse(read('schemas/seckit.schema.json')), 'manifest');
  ajv.addSchema(JSON.parse(read('schemas/attestations.schema.json')), 'attestations');
  exportsMap.manifest = 'manifest';
  exportsMap.attestations = 'attestations';
  for (const c of components) {
    if (!c.options) continue;
    const name = `options_${c.id}`;
    ajv.addSchema(c.options, name);
    exportsMap[name] = name;
  }
  let code = standaloneCode(ajv, exportsMap);
  // Node ESM needs file extensions on Ajv's deep runtime imports; bundlers accept them too.
  code = code.replace(/require\("ajv\/dist\/runtime\/([\w]+)"\)/g, (_, m) => `__rt_${m}`);
  const runtimes = [...new Set([...code.matchAll(/__rt_(\w+)/g)].map((m) => m[1]))];
  // Ajv's runtime helpers are CommonJS with `exports.default`. Node ESM exposes them as ns.default.default,
  // bundlers (esbuild/Vite interop) as ns.default — accept both.
  const imports = runtimes
    .map((m) => `import * as __rt_${m}_ns from 'ajv/dist/runtime/${m}.js';\nconst __rt_${m} = { default: __rt_${m}_ns.default?.default ?? __rt_${m}_ns.default };`)
    .join('\n');
  const validators = HEADER + '// @ts-nocheck\n/* eslint-disable */\n' + imports + '\n' + code + '\n';
  return { kbData, validators };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { kbData, validators } = generate();
  writeFileSync(new URL('../src/generated/kb-data.ts', import.meta.url), kbData);
  writeFileSync(new URL('../src/generated/validators.ts', import.meta.url), validators);
  console.log('wrote src/generated/kb-data.ts and src/generated/validators.ts');
}
