import type { ResolvedPlan } from '../types.js';

export interface Snippet {
  path: string;
  content: string;
}

const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by Security Kit for MPLAT-C1, MPLAT-C2 and MPLAT-C3.
  Copy to app/src/main/res/xml/network_security_config.xml and reference it from the manifest:
    <application android:networkSecurityConfig="@xml/network_security_config" ...>
-->
<network-security-config>
    <!-- MPLAT-C1: HTTPS only. MPLAT-C2: trust only the system CAs, never user-installed ones. -->
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>

    <!--
      MPLAT-C3 (assurance level 3): pin your API's public keys. Always include a backup pin and an
      expiration date; a wrong pin cuts the app off from your API. Replace the placeholders, then uncomment.
    <domain-config>
        <domain includeSubdomains="true">api.example.com</domain>
        <pin-set expiration="2027-12-31">
            <pin digest="SHA-256">REPLACE_WITH_BASE64_SPKI_SHA256_OF_CURRENT_KEY=</pin>
            <pin digest="SHA-256">REPLACE_WITH_BASE64_SPKI_SHA256_OF_BACKUP_KEY=</pin>
        </pin-set>
    </domain-config>
    -->

    <!-- Debug builds only: allow user CAs so you can inspect traffic with a proxy. Ignored in release. -->
    <debug-overrides>
        <trust-anchors>
            <certificates src="user" />
        </trust-anchors>
    </debug-overrides>
</network-security-config>
`;

const DATA_EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by Security Kit for MSTORE-C4. Keeps app data out of cloud backups and device transfers.
  Copy to app/src/main/res/xml/data_extraction_rules.xml and reference it from the manifest:
    <application android:dataExtractionRules="@xml/data_extraction_rules"
                 android:fullBackupContent="false" ...>
  (fullBackupContent covers Android 11 and lower.) Re-include anything that is safe to back up.
-->
<data-extraction-rules>
    <cloud-backup>
        <exclude domain="sharedpref" path="." />
        <exclude domain="database" path="." />
        <exclude domain="file" path="." />
    </cloud-backup>
    <device-transfer>
        <exclude domain="sharedpref" path="." />
        <exclude domain="database" path="." />
        <exclude domain="file" path="." />
    </device-transfer>
</data-extraction-rules>
`;

const ATS_PLIST = `<!--
  Generated by Security Kit for MPLAT-C1 and MPLAT-C3. Merge into your app's Info.plist.
  App Transport Security is on by default: never add NSAllowsArbitraryLoads or insecure exceptions.
-->
<key>NSAppTransportSecurity</key>
<dict>
    <key>NSAllowsArbitraryLoads</key>
    <false/>
    <!--
      MPLAT-C3 (assurance level 3, iOS 14+): pin your API's public keys, including a backup key.
      Replace the placeholders, then uncomment.
    <key>NSPinnedDomains</key>
    <dict>
        <key>api.example.com</key>
        <dict>
            <key>NSIncludesSubdomains</key>
            <true/>
            <key>NSPinnedLeafIdentities</key>
            <array>
                <dict>
                    <key>SPKI-SHA256-BASE64</key>
                    <string>REPLACE_WITH_BASE64_SPKI_SHA256_OF_CURRENT_KEY=</string>
                </dict>
                <dict>
                    <key>SPKI-SHA256-BASE64</key>
                    <string>REPLACE_WITH_BASE64_SPKI_SHA256_OF_BACKUP_KEY=</string>
                </dict>
            </array>
        </dict>
    </dict>
    -->
</dict>
`;

/** Platform config templates for the controls in this plan. */
export function renderSnippets(plan: ResolvedPlan): Snippet[] {
  const has = (component: string) => plan.components.some((c) => c.component.id === component);
  const platforms = plan.app.platforms;
  const out: Snippet[] = [];
  if (platforms.includes('android') && has('mobile_platform')) {
    out.push({ path: '.seckit/snippets/android/network_security_config.xml', content: NETWORK_SECURITY_CONFIG });
  }
  if (platforms.includes('android') && has('mobile_storage')) {
    out.push({ path: '.seckit/snippets/android/data_extraction_rules.xml', content: DATA_EXTRACTION_RULES });
  }
  if (platforms.includes('ios') && has('mobile_platform')) {
    out.push({ path: '.seckit/snippets/ios/app-transport-security.plist.xml', content: ATS_PLIST });
  }
  return out;
}
