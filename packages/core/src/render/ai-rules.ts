import type { AiAssistant, ResolvedPlan } from '../types.js';
import { uniqueControls } from './format.js';

/**
 * "managed" files belong to the developer: only the marked block is written.
 * "owned" files belong entirely to Security Kit and are overwritten.
 */
export const AI_FILES: Record<AiAssistant, { path: string; mode: 'managed' | 'owned' }> = {
  agents_md: { path: 'AGENTS.md', mode: 'managed' },
  claude: { path: 'CLAUDE.md', mode: 'managed' },
  cursor: { path: '.cursor/rules/security-kit.mdc', mode: 'owned' },
  copilot: { path: '.github/copilot-instructions.md', mode: 'managed' },
};

export const BLOCK_BEGIN = '<!-- BEGIN SECURITY KIT: generated by `seckit generate`; edits inside this block are overwritten -->';
export const BLOCK_END = '<!-- END SECURITY KIT -->';
const BEGIN_PREFIX = '<!-- BEGIN SECURITY KIT';

export function renderRules(plan: ResolvedPlan): string {
  const L: string[] = [
    '## Security rules (Security Kit)',
    '',
    `This project follows a tailored security plan for **${plan.app.name}** in \`.seckit/SECURITY-PLAN.md\`.`,
    'These rules are requirements, not suggestions. Apply them whenever you write, change or review code.',
    '',
    '- If a request would break a rule, say so and propose a compliant alternative instead of silently complying.',
    '- When code implements or touches a control, mention its ID (e.g. `AUTH-C2`) in the summary or PR description.',
    '- For the full reasoning and verification steps, read the control in `.seckit/SECURITY-PLAN.md` or run `npx seckit explain <ID>`.',
    '- If the `seckit` MCP server is connected: call `get_controls_for_file` before editing a file and `check_code` on new or changed code before finishing.',
    '- Never add or change entries in `.seckit/attestations.yaml`; sign-offs are made by people.',
  ];

  let heading = '';
  for (const { heading: h, control } of uniqueControls(plan)) {
    if (h !== heading) {
      L.push('', `### ${h}`, '');
      heading = h;
    }
    L.push(`- **${control.id}** (${control.severity}): ${control.ai_rule}`);
  }
  return L.join('\n') + '\n';
}

export function renderCursorRule(rules: string, version: string): string {
  return [
    '---',
    'description: Security rules for this project, generated by Security Kit. Follow them for every code change.',
    'alwaysApply: true',
    '---',
    `<!-- Generated by Security Kit ${version} (\`seckit generate\`). Do not edit; change seckit.yaml and regenerate. -->`,
    '',
    rules,
  ].join('\n');
}

/** Insert or replace the Security Kit block in a developer-owned file, leaving everything else untouched. */
export function mergeManagedBlock(existing: string | undefined, block: string): string {
  const wrapped = `${BLOCK_BEGIN}\n${block.trimEnd()}\n${BLOCK_END}\n`;
  if (existing === undefined || existing.trim() === '') return wrapped;

  const start = existing.indexOf(BEGIN_PREFIX);
  const end = existing.indexOf(BLOCK_END);
  if (start === -1 && end === -1) return `${existing.trimEnd()}\n\n${wrapped}`;
  if (start === -1 || end === -1 || end < start) {
    throw new Error('Found an unbalanced Security Kit block (BEGIN/END markers). Fix or remove the markers and retry.');
  }
  return existing.slice(0, start) + wrapped + existing.slice(end + BLOCK_END.length).replace(/^\r?\n/, '');
}
